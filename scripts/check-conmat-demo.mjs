import assert from 'node:assert/strict';
const memory=new Map();
globalThis.localStorage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
globalThis.window={addEventListener(){}};
const model=await import('../src/web/conmat-demo-store.js');
const portal=await import('../src/web/conmat-carrier-model.js');
const initialPortal=portal.carrierWorkspace(model.initialRoutes,model.initialOrders,'caribe');
assert.deepEqual(initialPortal.routes.map(route=>route.id),['R-001','R-003']);
assert.ok(initialPortal.orders.every(order=>order.carrierId==='caribe'));
assert.equal(new Set(initialPortal.notifications.map(item=>item.id)).size,initialPortal.notifications.length);
assert.equal(portal.carrierWorkspace(model.initialRoutes,model.initialOrders,'ajena').routes.length,0);
assert.equal(portal.portalMaterials(initialPortal.routes[0],initialPortal.orders).find(item=>item.name==='Estibas').quantity,20);
const key='sial-conmat-demo-orders-v1';
const saved=()=>JSON.parse(memory.get(key));
assert.equal(model.initialOrders.length,22);
for(const route of model.routeFixtures){
 const linked=model.initialOrders.filter(order=>order.routeId===route.id);
 assert.equal(linked.length,route.orders);
 for(const [name,total,unit] of route.qty)assert.equal(model.materialTotals(linked).find(line=>line.name===name&&line.unit===unit)?.quantity,total);
}
model.preassignOrders(['OS-04801'],'caribe');
const id=model.saveConmatRoute({name:'Ruta integrada de prueba',carrierId:'caribe',plannedDate:'2026-11-24'});
assert.equal(id,'R-007');
assert.ok(!portal.carrierWorkspace(saved().routes,saved().orders,'caribe').routes.some(route=>route.id===id));
const tripId=model.saveConmatLevel({routeId:id,kind:'trip',name:'Viaje de prueba'});
const groupA=model.saveConmatLevel({routeId:id,tripId,kind:'group',name:'Subgrupo A'});
const groupB=model.saveConmatLevel({routeId:id,tripId,kind:'group',name:'Subgrupo B'});
assert.throws(()=>model.confirmConmatRoute(id));
model.moveConmatOrders({routeId:id,ids:['OS-04809'],fromGroupId:'available',toGroupId:groupA});
model.moveConmatOrders({routeId:id,ids:['OS-04801'],fromGroupId:'available',toGroupId:groupB});
assert.throws(()=>model.moveConmatOrders({routeId:id,ids:['OS-04809'],fromGroupId:'available',toGroupId:groupB}));
assert.throws(()=>model.moveConmatOrders({routeId:id,ids:['OS-04810'],fromGroupId:'available',toGroupId:groupB}));
assert.throws(()=>model.moveConmatOrders({routeId:id,ids:['OS-04802'],fromGroupId:'available',toGroupId:groupB}));
assert.throws(()=>model.moveConmatOrders({routeId:'R-003',ids:['OS-04809'],fromGroupId:groupA,toGroupId:'available'}));
assert.throws(()=>model.preassignOrders(['OS-04809'],'norte'));
assert.equal(model.routeProgrammingIssues(saved().routes.find(route=>route.id===id),saved().orders).length,0);
model.confirmConmatRoute(id);
assert.ok(portal.carrierWorkspace(saved().routes,saved().orders,'caribe').routes.some(route=>route.id===id));
assert.ok(saved().orders.filter(order=>order.routeId===id).every(order=>order.status==='Programada'));
assert.equal(model.summarizeRoute(saved().routes.find(route=>route.id===id),saved().orders).orders,2);
model.moveConmatOrders({routeId:id,ids:['OS-04801'],fromGroupId:groupB,toGroupId:groupA});
assert.equal(saved().orders.filter(order=>order.id==='OS-04801').length,1);
model.moveConmatOrders({routeId:id,ids:['OS-04801'],fromGroupId:groupA,toGroupId:'available'});
assert.equal(saved().orders.find(order=>order.id==='OS-04801').status,'Preasignada');
assert.equal(saved().orders.find(order=>order.id==='OS-04801').routeId,null);
assert.equal(saved().orders.length,22);
assert.ok(saved().routes.find(route=>route.id===id).events.length>=6);
const change={routeId:'R-001',action:'cancel',scope:'orders',ids:['OS-04812'],reason:'Solicitud de la finca'};
const beforeChange=memory.get(key);
assert.throws(()=>model.previewConmatProgrammingChange({...change,reason:' '}));
assert.throws(()=>model.previewConmatProgrammingChange({...change,ids:['OS-04801']}));
assert.throws(()=>model.previewConmatProgrammingChange({...change,routeId:'R-003',ids:['OS-04816']}));
assert.equal(model.previewConmatProgrammingChange(change).orders.length,1);
assert.equal(memory.get(key),beforeChange,'Revisar no debe mutar el estado');
model.changeConmatProgramming(change);
assert.equal(saved().orders.find(order=>order.id==='OS-04812').status,'Preasignada');
assert.equal(saved().orders.find(order=>order.id==='OS-04812').programmingStatus,'Cancelada');
assert.equal(saved().orders.find(order=>order.id==='OS-04813').routeId,'R-001');
assert.equal(model.summarizeRoute(saved().routes.find(route=>route.id==='R-001'),saved().orders).orders,2);
const reschedule={routeId:'R-001',action:'reschedule',scope:'orders',ids:['OS-04813'],date:'2026-11-28',reason:'Nueva fecha de entrega'};
assert.throws(()=>model.changeConmatProgramming({...reschedule,date:'2026-02-30'}));
assert.throws(()=>model.changeConmatProgramming({...reschedule,expectedIds:['OS-04814']}));
model.changeConmatProgramming(reschedule);
assert.equal(saved().orders.find(order=>order.id==='OS-04813').plannedDate,'2026-11-28');
assert.equal(saved().routes.find(route=>route.id==='R-001').plannedDate,'2026-11-23');
assert.ok(!saved().orders.find(order=>order.id==='OS-04814').plannedDate);
model.changeConmatProgramming({routeId:'R-002',action:'reschedule',scope:'group',targetId:'R-002-V01-S01',date:'2026-11-29',reason:'Entrega parcial'});
assert.equal(saved().orders.find(order=>order.id==='OS-04815').plannedDate,'2026-11-29');
model.changeConmatProgramming({routeId:'R-002',action:'reschedule',scope:'route',date:'2026-11-30',reason:'Cambio de toda la ruta'});
assert.ok(saved().orders.filter(order=>order.routeId==='R-002').every(order=>order.plannedDate==='2026-11-30'));
model.moveConmatOrders({routeId:'R-001',ids:['OS-04812'],fromGroupId:'available',toGroupId:'R-001-V01-S01'});
assert.equal(saved().orders.find(order=>order.id==='OS-04812').programmingStatus,null);
assert.ok(saved().orders.find(order=>order.id==='OS-04812').events.some(event=>event.programmingStatus==='Cancelada'));
model.changeConmatProgramming({routeId:'R-001',action:'annul',scope:'trip',targetId:'R-001-V01',reason:'Viaje no requerido'});
assert.equal(saved().routes.find(route=>route.id==='R-001').trips[0].programmingStatus,'Anulado');
assert.equal(saved().orders.filter(order=>order.routeId==='R-001').length,0);
assert.throws(()=>model.moveConmatOrders({routeId:'R-001',ids:['OS-04812'],fromGroupId:'available',toGroupId:'R-001-V01-S01'}));
assert.throws(()=>model.saveConmatLevel({routeId:'R-001',tripId:'R-001-V01',kind:'group',name:'No permitido'}));
assert.equal(saved().orders.length,22);
assert.ok(saved().routes.find(route=>route.id==='R-002').events.at(-1).reason);
const initialMigration=model.initialOrders.map(order=>order.id==='OS-04801'?{...order,status:'Preasignada',carrierId:'caribe'}:order);
memory.set(key,JSON.stringify({version:1,orders:initialMigration}));
const migrated=await import('../src/web/conmat-demo-store.js?migration');
migrated.saveConmatRoute({name:'Migración',carrierId:'caribe',plannedDate:''});
assert.equal(saved().version,2);
assert.equal(saved().orders.find(order=>order.id==='OS-04801').carrierId,'caribe');
assert.ok(saved().orders.filter(order=>order.routeId).every(order=>order.tripId&&order.subgroupId));
console.log('CONMAT: fixtures, migración v1→v2, ruta/viaje/subgrupo, movimiento, restricciones, totales y programación verificados.');
