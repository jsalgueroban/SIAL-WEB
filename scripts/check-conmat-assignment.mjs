import assert from 'node:assert/strict';
const memory=new Map();
globalThis.localStorage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
globalThis.window={addEventListener(){}};
const model=await import('../src/web/conmat-demo-store.js');
const assignment=await import('../src/web/conmat-assignment-model.js');
const key='sial-conmat-demo-orders-v1',saved=()=>JSON.parse(memory.get(key));
model.preassignOrders(['OS-04801'],'caribe');
const base={companyId:'caribe',routeId:'R-001',scope:'route',targetId:'R-001',vehicleId:'caribe-vehicle-2',driverId:'caribe-driver-2',date:'2026-11-23',start:'08:00',end:'12:00'};
const prior=memory.get(key);
assert.equal(model.previewConmatAssignment(base).orders.length,3);
assert.equal(memory.get(key),prior,'Revisar no escribe');
assert.throws(()=>model.previewConmatAssignment({...base,vehicleId:'caribe-vehicle-3'}),error=>error.field==='vehicle');
assert.throws(()=>model.previewConmatAssignment({...base,driverId:'caribe-driver-3'}),error=>error.field==='driver');
assert.throws(()=>model.previewConmatAssignment({...base,vehicleId:'caribe-vehicle-1'}),error=>error.field==='vehicle'&&error.message.includes('R-003'));
assert.throws(()=>model.previewConmatAssignment({...base,driverId:'caribe-driver-1'}),error=>error.field==='driver');
assert.throws(()=>model.previewConmatAssignment({...base,routeId:'R-003',targetId:'R-003'}),error=>error.field==='route');
assert.throws(()=>model.previewConmatAssignment({...base,routeId:'R-002',targetId:'R-002'}),error=>error.field==='route');
assert.throws(()=>model.previewConmatAssignment({...base,end:'07:00'}),error=>error.field==='end');
assert.throws(()=>model.previewConmatAssignment({...base,start:'25:00'}),error=>error.field==='start');
model.saveConmatAssignment(base);
assert.equal(saved().routes[0].state,1);
assert.equal(saved().orders.length,22);
const replacement={...base,vehicleId:'caribe-vehicle-1',driverId:'caribe-driver-1',start:'14:00',end:'16:00'};
assert.throws(()=>model.saveConmatAssignment(replacement),error=>error.field==='reason');
model.saveConmatAssignment({...replacement,reason:'Reemplazo del vehículo por disponibilidad'});
assert.equal(saved().routes[0].assignments.length,1);
assert.ok(saved().routes[0].events.at(-1).before.includes('KLM-456'));
assert.ok(saved().routes[0].events.at(-1).after.includes('WFX-123'));
assert.equal(saved().routes[0].events.at(-1).actor,'Operador de transporte');
assert.throws(()=>model.previewConmatAssignment({...replacement,reason:'Sin cambios'}),error=>error.field==='form');
assert.throws(()=>model.previewConmatAssignment({...base,scope:'group',targetId:'R-001-V01-S01'}),error=>error.field==='scope');
const id=model.saveConmatRoute({name:'Ruta por subgrupos',carrierId:'caribe',plannedDate:'2026-11-24'});
const tripId=model.saveConmatLevel({routeId:id,kind:'trip',name:'Viaje 1'});
const groupA=model.saveConmatLevel({routeId:id,tripId,kind:'group',name:'Grupo A'});
const groupB=model.saveConmatLevel({routeId:id,tripId,kind:'group',name:'Grupo B'});
model.moveConmatOrders({routeId:id,ids:['OS-04801'],fromGroupId:'available',toGroupId:groupA});
model.moveConmatOrders({routeId:id,ids:['OS-04809'],fromGroupId:'available',toGroupId:groupB});
model.confirmConmatRoute(id);
const part={...base,routeId:id,scope:'group',targetId:groupA,date:'2026-11-24',start:'08:00',end:'10:00'};
model.saveConmatAssignment(part);
assert.equal(saved().routes.find(route=>route.id===id).state,0);
assert.match(saved().routes.find(route=>route.id===id).note,/parcial/);
assert.throws(()=>model.saveConmatAssignment({...part,targetId:groupB,start:'09:00',end:'11:00'}),error=>error.field==='vehicle');
model.saveConmatAssignment({...part,targetId:groupB,vehicleId:'caribe-vehicle-1',driverId:'caribe-driver-1',start:'10:00',end:'12:00'});
assert.equal(saved().routes.find(route=>route.id===id).state,1);
assert.throws(()=>model.saveConmatAssignment({...part,reason:'Cambio',end:'11:00',expectedIds:['otra-orden']}),error=>error.field==='form');
model.changeConmatProgramming({routeId:id,action:'reschedule',scope:'group',targetId:groupA,date:'2026-11-25',reason:'Nueva entrega'});
const changedRoute=saved().routes.find(route=>route.id===id);
assert.equal(changedRoute.state,0);
assert.equal(assignment.assignmentApplies(changedRoute,changedRoute.assignments[0],saved().orders),false);
assert.throws(()=>model.previewConmatAssignment({...part,reason:'Ajustar fecha'}),error=>error.field==='date');
model.saveConmatAssignment({...part,date:'2026-11-25',reason:'Ajuste por nueva programación'});
assert.equal(saved().routes.find(route=>route.id===id).state,1);
model.saveConmatRoute({id,name:'Otra transportadora',carrierId:'norte',plannedDate:'2026-11-24'});
assert.equal(saved().routes.find(route=>route.id===id).assignments.length,0);
assert.equal(saved().routes.find(route=>route.id===id).state,0);
assert.equal(saved().orders.length,22);
console.log('CONMAT CA07: alcance, recursos habilitados, cruces, revisión sin escritura, reemplazo, cobertura parcial/completa y reprogramación verificados.');
