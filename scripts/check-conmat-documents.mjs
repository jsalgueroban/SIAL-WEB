import assert from 'node:assert/strict';
const memory=new Map();
globalThis.localStorage={getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)};
globalThis.window={addEventListener(){}};
const model=await import('../src/web/conmat-demo-store.js');
const tracking=await import('../src/web/conmat-tracking-model.js');
const key='sial-conmat-demo-orders-v1',saved=()=>JSON.parse(memory.get(key));
model.preassignOrders(['OS-04801'],'caribe');
const rows=()=>tracking.trackingRows(saved().routes,saved().orders,'caribe');
assert.deepEqual(rows().map(row=>row.route.id),['R-003']);
assert.ok(tracking.trackingRows(saved().routes,saved().orders,'desconocida').length===0);
const initial=rows()[0],seedIssue=initial.issues[0];
assert.equal(initial.record.stage,'En operación');
assert.equal(tracking.nextTrackingStep(initial.record).id,'arrive');
assert.equal(tracking.trackingDelay(initial,new Date('2026-11-24T15:00:00Z').getTime()),'Fin estimado vencido');
const command={companyId:'caribe',routeId:'R-003',targetId:'R-003'};
assert.throws(()=>model.recordConmatTracking({...command,companyId:'norte',action:'issue',observation:'No permitido'}));
assert.throws(()=>model.recordConmatTracking({...command,action:'issue',observation:' '}),error=>error.field==='observation');
assert.throws(()=>model.recordConmatTracking({...command,action:'milestone',step:'deliver'}));
model.recordConmatTracking({...command,action:'resolve',issueId:seedIssue.id,observation:'Ingreso autorizado en la finca'});
let current=rows()[0];
assert.equal(current.issues.length,0);
assert.equal(current.record.issues[0].observation,seedIssue.observation);
assert.equal(current.record.issues[0].resolution,'Ingreso autorizado en la finca');
assert.ok(current.record.issues[0].resolvedAt);
assert.ok(!current.route.note.startsWith('Novedad'));
assert.throws(()=>model.recordConmatTracking({...command,action:'resolve',issueId:seedIssue.id,observation:'Duplicada'}));
model.recordConmatTracking({...command,action:'issue',observation:'Lluvia en la vía'});
assert.equal(rows()[0].issues.length,1);
assert.match(saved().routes.find(route=>route.id==='R-003').note,/Lluvia/);
model.recordConmatTracking({...command,action:'milestone',step:'arrive'});
assert.equal(tracking.nextTrackingStep(rows()[0].record).id,'deliver');
const before=memory.get(key);
assert.throws(()=>model.recordConmatTracking({...command,action:'milestone',step:'arrive'}));
assert.equal(memory.get(key),before);
assert.throws(()=>model.recordConmatTracking({...command,action:'milestone',step:'deliver',assignmentKey:'obsoleta'}));
model.saveConmatAssignment({companyId:'caribe',routeId:'R-001',scope:'route',targetId:'R-001',vehicleId:'caribe-vehicle-2',driverId:'caribe-driver-2',date:'2026-11-23',start:'08:00',end:'12:00'});
const first={companyId:'caribe',routeId:'R-001',targetId:'R-001',action:'milestone'};
model.recordConmatTracking({...first,step:'prepare'});
assert.equal(rows().find(row=>row.route.id==='R-001').record.stage,'Pendiente de salida');
model.recordConmatTracking({...first,step:'depart'});
assert.equal(saved().routes.find(route=>route.id==='R-001').state,2);
assert.throws(()=>model.saveConmatRoute({id:'R-001',name:'Bloqueada',carrierId:'caribe',plannedDate:'2026-11-23'}));
for(const step of ['arrive','deliver','return'])model.recordConmatTracking({...first,step});
const operated=rows().find(row=>row.route.id==='R-001');
assert.equal(tracking.nextTrackingStep(operated.record),null);
assert.equal(operated.route.state,2,'El retorno no finaliza ni aprueba documentación');
assert.match(operated.route.note,/Pendiente de cierre/);
assert.ok(operated.record.events.every(event=>event.at&&event.actor));
assert.equal(tracking.trackingIndicators(rows()).find(item=>item.label==='En operación').value,2);
assert.throws(()=>model.recordConmatTracking({companyId:'rutas',routeId:'R-004',targetId:'R-004',action:'issue',observation:'Finalizado'}));
assert.equal(saved().orders.length,22);
console.log('CONMAT CA08: alcance por empresa, hitos ordenados, novedades preservadas, actor/fecha, atraso, bloqueo y sincronización verificados.');

const closure=await import('../src/web/conmat-closure-model.js');
const route=()=>saved().routes.find(route=>route.id==='R-001');
let review=closure.closureReview(route(),saved().orders);
assert.equal(review.ready,true);
assert.throws(()=>model.closeConmatRoute({companyId:'norte',routeId:'R-001',signature:review.signature}));
assert.throws(()=>model.closeConmatRoute({companyId:'caribe',routeId:'R-001',signature:'obsoleto'}));
assert.equal(closure.closureReview({...route(),phase:'Cancelada'},saved().orders).ready,false);
assert.equal(closure.closureReview({...route(),programmingStatus:'Anulado'},saved().orders).ready,false);
assert.equal(closure.closureReview(route(),saved().orders.map(order=>order.routeId==='R-001'?{...order,status:'Cancelada'}:order)).ready,false);
assert.equal(closure.closureReview(saved().routes.find(route=>route.id==='R-003'),saved().orders).ready,false);
const docs=route().docs;
model.closeConmatRoute({companyId:'caribe',routeId:'R-001',signature:review.signature,observation:'Retorno y entrega verificados'});
assert.equal(route().state,3);
assert.equal(route().docs,docs);
assert.ok(route().closure.at&&route().closure.actor);
assert.equal(route().closure.observation,'Retorno y entrega verificados');
assert.equal(rows().find(row=>row.route.id==='R-001').record.stage,'Finalizada');
assert.equal(rows().find(row=>row.route.id==='R-001').record.events.at(-1).kind,'close');
assert.throws(()=>model.closeConmatRoute({companyId:'caribe',routeId:'R-001',signature:review.signature}));
assert.throws(()=>model.recordConmatTracking({...first,step:'return'}));
console.log('CONMAT CA09: cierre completo, actor/fecha, obsolescencia, cancelación, anulación, duplicados y documentación independiente verificados.');

const docsModel=await import('../src/web/conmat-documents-model.js');
let file={id:'local-1',name:'entrega.pdf',type:'application/pdf',size:512};
const supportCmd={action:'upload',companyId:'caribe',routeId:'R-001',expectedVersion:0,file};
assert.throws(()=>model.saveConmatSupport({...supportCmd,companyId:'norte'}));
assert.throws(()=>model.saveConmatSupport({...supportCmd,routeId:'R-003'}));
assert.throws(()=>model.saveConmatSupport({...supportCmd,file:{...file,size:11*1024*1024}}));
model.saveConmatSupport(supportCmd);
assert.equal(route().docs,'Soporte cargado');
assert.equal(route().documentVersions[0].services[0],'R-001');
assert.ok(route().documentVersions[0].at&&route().documentVersions[0].actor);
assert.throws(()=>model.saveConmatSupport({...supportCmd,expectedVersion:1}));
model.saveConmatSupport({...supportCmd,action:'submit',expectedVersion:1});
assert.equal(route().docs,'En revisión');
assert.equal(route().state,3);
assert.throws(()=>model.saveConmatSupport({...supportCmd,expectedVersion:1}));
const rejected={...route(),documentVersions:[{...route().documentVersions[0],status:'Rechazado',reviewObservation:'Documento ilegible'}]};
assert.equal(docsModel.canUploadSupport(rejected),true);
assert.doesNotThrow(()=>docsModel.validateSupportCommand([rejected],{...supportCmd,expectedVersion:1}));
assert.throws(()=>docsModel.validateSupportCommand([rejected],{...supportCmd,expectedVersion:0}));
assert.equal(await docsModel.inspectSupportFile(new File(['%PDF-1.4 ejemplo'],'archivo.pdf',{type:'application/pdf'})),'application/pdf');
await assert.rejects(()=>docsModel.inspectSupportFile(new File(['texto'],'archivo.pdf')));
await assert.rejects(()=>docsModel.inspectSupportFile(new File(['%PDF-1.4'],'archivo.png')));
console.log('CONMAT CA10: alcance, cierre previo, formato/tamaño, versiones, rechazo, metadatos y envío a revisión verificados.');
