async page => {
  const failures=[];
  page.on('pageerror',error=>failures.push(error.message));
  const base='http://127.0.0.1:8765/Calidad/inspecciones.html';
  const check=async(condition,message)=>{if(!await condition)throw new Error(message);};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base);
  if(await page.getByRole('button',{name:'Cambiar a modo claro',exact:true}).count()) await page.getByRole('button',{name:'Cambiar a modo claro',exact:true}).click();
  await page.getByRole('heading',{name:'Inspecciones de calidad',exact:true}).waitFor();
  await check(page.locator('.qc-canvas figure').count().then(n=>n===3),'Tres gráficas de librería montadas');
  await page.getByRole('textbox',{name:'Buscar inspección',exact:true}).fill('PL-8459');
  await check(page.getByRole('button',{name:'Revisar IC-01481',exact:true}).count().then(n=>n===1),'Búsqueda por pallet');
  await page.getByRole('button',{name:'Revisar IC-01481',exact:true}).click();
  await page.getByRole('button',{name:'Cinco cajas',exact:true}).click();
  for(let i=1;i<=5;i++){
    await page.getByRole('button',{name:`Caja ${i}`,exact:true}).click();
    await check(page.getByRole('heading',{name:`Caja ${i}`,exact:true}).count().then(n=>n===1),`Detalle caja ${i}`);
  }
  await page.screenshot({path:'output/quality-five-boxes-desktop.png'});
  await page.getByRole('button',{name:'Evidencias',exact:true}).click();
  await page.locator('.qi-evidence').first().click();
  await check(page.locator('dialog[open]').count().then(n=>n===1),'Ficha de evidencia abierta');
  await page.keyboard.press('Escape');
  await check(page.locator('dialog[open]').count().then(n=>n===0),'Escape cierra evidencia');
  await page.getByRole('button',{name:'Revisión supervisora',exact:true}).click();
  await page.getByRole('button',{name:'Guardar revisión',exact:true}).click();
  await check(page.getByRole('alert').textContent().then(t=>t.includes('tres comprobaciones')),'Bloqueo de revisión incompleta');
  for(const label of ['Contexto y trazabilidad','Cinco cajas y resultados','Defectos y evidencias']) { await page.getByText(label,{exact:true}).click(); await check(page.getByRole('checkbox',{name:label,exact:true}).isChecked(),'Comprobación seleccionada'); }
  await page.getByRole('button',{name:'Guardar revisión',exact:true}).click();
  await check(page.getByRole('alert').textContent().then(t=>t.includes('observación')),'Comentario obligatorio');
  await page.locator('#qi-comment').fill('Validación de demostración: cinco cajas y trazabilidad revisadas.');
  await page.getByRole('button',{name:'Guardar revisión',exact:true}).click();
  await check(page.getByRole('status').textContent().then(t=>t.includes('guardada')),'Decisión guardada');
  await page.screenshot({path:'output/quality-supervisor-desktop.png'});
  await page.getByRole('button',{name:'Volver a inspecciones',exact:true}).click();
  await check(page.getByRole('textbox',{name:'Buscar inspección',exact:true}).inputValue().then(t=>t==='PL-8459'),'Filtro conservado al volver');
  await page.reload();
  await page.getByRole('button',{name:'Revisar IC-01481',exact:true}).click();
  await page.getByRole('button',{name:'Trazabilidad',exact:true}).click();
  await check(page.locator('.qi-timeline').textContent().then(t=>t.includes('Validación de demostración')),'Revisión persiste y aparece en trazabilidad');
  await page.screenshot({path:'output/quality-traceability-desktop.png'});
  await page.getByRole('button',{name:'Volver a inspecciones',exact:true}).click();
  await page.getByRole('button',{name:'Analítica',exact:true}).click();
  await page.getByRole('button',{name:'Rechazo total: 3 inspecciones',exact:true}).click();
  await check(page.locator('.qi-register tbody tr').count().then(n=>n===3),'Selección de resultado filtra tabla');
  await page.getByRole('button',{name:'Semana 48',exact:true}).click();
  await check(page.locator('.qi-register tbody tr').count().then(n=>n===1),'Cruce de semana y resultado');
  await page.goto(base);
  await page.getByRole('button',{name:'Siguiente',exact:true}).click();
  await check(page.locator('.qi-register').textContent().then(t=>t.includes('6-10')),'Paginación');
  await page.getByRole('textbox',{name:'Buscar inspección',exact:true}).fill('SIN-COINCIDENCIAS');
  await check(page.getByRole('heading',{name:'No hay inspecciones con estos filtros',exact:true}).count().then(n=>n===1),'Estado vacío');
  await page.getByRole('button',{name:'Restablecer consulta',exact:true}).click();
  await page.getByRole('button',{name:'Analítica',exact:true}).click();
  await page.getByRole('button',{name:'Cambiar a modo oscuro',exact:true}).click();
  await page.screenshot({path:'output/quality-analytics-dark.png'});
  await page.setViewportSize({width:390,height:844});
  await check(page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Sin overflow global móvil');
  await page.screenshot({path:'output/quality-analytics-mobile-dark.png'});
  await page.getByRole('button',{name:'Revisar IC-01482',exact:true}).click();
  await page.getByRole('button',{name:'Revisión supervisora',exact:true}).click();
  await check(page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Formulario móvil sin overflow');
  await page.screenshot({path:'output/quality-review-mobile-dark.png'});
  await page.getByRole('button',{name:'Cambiar a modo claro',exact:true}).click();
  await page.goto(`${base}?estado=error`);
  await page.getByRole('button',{name:'Reintentar',exact:true}).click();
  await check(page.getByRole('heading',{name:'Inspecciones registradas',exact:true}).count().then(n=>n===1),'Recuperación de error');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(`${base}?vista=analitica`);
  await page.evaluate(()=>localStorage.removeItem('sial-quality-review-demo-v1'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('.qc-canvas figure svg').length===3);
  await page.screenshot({path:'output/quality-final-analytics.png'});
  await check(Promise.resolve(failures.length===0),`Errores de runtime: ${failures.join('; ')}`);
  return 'PASS: tres gráficos, búsqueda, cinco cajas, evidencias, validación, persistencia, retorno, filtros cruzados, paginación, vacío, error, oscuro y móvil.';
}
